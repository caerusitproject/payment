-- PostgreSQL schema for Payment Service. Apply before starting with ddl-auto=validate.
CREATE TABLE IF NOT EXISTS c3_payer (
 payer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 payer_bank_name VARCHAR(150) NOT NULL, payer_branch VARCHAR(150), payer_name VARCHAR(150),
 acc_num_encrypted BYTEA, acc_num_masked VARCHAR(30), ifsc_code VARCHAR(11),
 currency CHAR(3) NOT NULL, adapter_prvdr VARCHAR(150) NOT NULL,
 active_status_cdid BOOLEAN NOT NULL, created_ts TIMESTAMPTZ NOT NULL, updated_ts TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS c3_pymnt_mode (
 pymnt_mode_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 mode_code VARCHAR(10) NOT NULL, mode_name VARCHAR(50) NOT NULL,
 min_amount NUMERIC(18,2) NOT NULL, max_amount NUMERIC(18,2) NOT NULL,
 active_status_cdid BOOLEAN NOT NULL, created_ts TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS pymnt_req (
 pymnt_req_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 req_ref_name VARCHAR(50) NOT NULL, req_ref_id BIGINT NOT NULL,
 ben_ref_entity_name VARCHAR(50) NOT NULL, ben_ref_entity_id BIGINT NOT NULL,
 payment_mode_id BIGINT, txn_categ_cdid VARCHAR(20) NOT NULL, ben_acct_id BIGINT NOT NULL,
 amount NUMERIC(18,2) NOT NULL, currency CHAR(3) NOT NULL,
 is_completed BOOLEAN NOT NULL DEFAULT FALSE, initiated_ts TIMESTAMPTZ NOT NULL, complete_ts TIMESTAMPTZ,
 queue_type VARCHAR(20) NOT NULL, proc_status VARCHAR(30) NOT NULL,
 retry_count INTEGER NOT NULL DEFAULT 0, next_attempt_at TIMESTAMPTZ, last_reason VARCHAR(1000),
 CONSTRAINT uk_pymnt_req_ref UNIQUE(req_ref_name, req_ref_id)
);
CREATE INDEX IF NOT EXISTS ix_pymnt_req_pick ON pymnt_req(queue_type, proc_status, next_attempt_at);
CREATE TABLE IF NOT EXISTS c3_benef_snapshot (
 beni_snap_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ben_ref_id BIGINT NOT NULL, ben_acct_hol_name VARCHAR(150) NOT NULL,
 ben_acc_encrypted BYTEA NOT NULL, ben_acc_masked VARCHAR(30) NOT NULL,
 ifsc_code VARCHAR(11) NOT NULL, bank_name VARCHAR(150), txn_categ_cdid VARCHAR(20),
 created_ts TIMESTAMPTZ NOT NULL, update_ts TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS c3_pymnt_txn (
 pymnt_txn_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pymnt_req_id BIGINT NOT NULL REFERENCES pymnt_req(pymnt_req_id),
 payer_id BIGINT NOT NULL REFERENCES c3_payer(payer_id), beneficiary_id BIGINT NOT NULL,
 beni_snap_id BIGINT REFERENCES c3_benef_snapshot(beni_snap_id),
 payment_mode_id BIGINT NOT NULL REFERENCES c3_pymnt_mode(pymnt_mode_id),
 amount NUMERIC(18,2) NOT NULL, remarks VARCHAR(100), currency CHAR(3) NOT NULL,
 attempt_num INTEGER NOT NULL, transaction_type VARCHAR(3) NOT NULL,
 unique_id VARCHAR(40) NOT NULL UNIQUE, urn VARCHAR(50),
 txn_status VARCHAR(30) NOT NULL, response VARCHAR(30) NOT NULL,
 resp_code VARCHAR(30), error_code VARCHAR(30), failure_message VARCHAR(1000),
 initiated_ts TIMESTAMPTZ NOT NULL, updated_ts TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_pymnt_txn_req_attempt ON c3_pymnt_txn(pymnt_req_id, attempt_num DESC);
CREATE TABLE IF NOT EXISTS c3_bank_api_interaction (
 api_interaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 api_operation VARCHAR(30) NOT NULL, unique_id VARCHAR(40), attempt_num INTEGER NOT NULL,
 http_status_code INTEGER, response VARCHAR(4000) NOT NULL,
 initiated_ts TIMESTAMPTZ NOT NULL, completed_ts TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_bank_api_uid ON c3_bank_api_interaction(unique_id, api_operation);
CREATE TABLE IF NOT EXISTS c3_worklist_item (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 item_type VARCHAR(30) NOT NULL, pymnt_req_id BIGINT NOT NULL,
 pymnt_txn_id BIGINT, unique_id VARCHAR(40), title VARCHAR(500) NOT NULL,
 detail VARCHAR(1000), amount NUMERIC(18,2), status VARCHAR(20) NOT NULL,
 otp_encrypted BYTEA, created_ts TIMESTAMPTZ NOT NULL, expires_ts TIMESTAMPTZ, completed_ts TIMESTAMPTZ
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_active_payment_otp
 ON c3_worklist_item(item_type) WHERE item_type = 'OTP_ENTRY' AND status = 'OPEN';
